INSERT INTO opinion_registro (id_usuario, autor_nombre, autor_correo, id_preparacion, categoria, fecha_menu, estrellas, comentario, creado_en)
SELECT u.id_usuario, u.nombre, u.email, p.id_preparacion, ctx.categoria, ctx.fecha, o.est, o.txt,
       COALESCE(ctx.fecha::timestamp + TIME '15:30', CURRENT_TIMESTAMP) - ((o.u % 5) * 37 || ' minutes')::interval
FROM _op o
JOIN preparacion p ON p.nombre = o.plato
JOIN usuario u ON u.email = 'estudiante.demo' || o.u || '@duocuc.cl'
LEFT JOIN LATERAL (
  SELECT c.nombre AS categoria, m.fecha
  FROM menu_preparacion mp
  JOIN menu m ON m.id_menu = mp.id_menu
  LEFT JOIN categoria_menu c ON c.id_categoria_menu = mp.id_categoria_menu
  WHERE mp.id_preparacion = p.id_preparacion
  ORDER BY m.fecha DESC LIMIT 1
) ctx ON TRUE;

