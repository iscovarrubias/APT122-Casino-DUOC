FROM menu_preparacion mp
JOIN menu m ON m.id_menu = mp.id_menu
WHERE m.fecha IN (SELECT fecha FROM _demo_menu)
  AND NOT EXISTS (SELECT 1 FROM disponibilidad d WHERE d.id_menu_preparacion = mp.id_menu_preparacion);

