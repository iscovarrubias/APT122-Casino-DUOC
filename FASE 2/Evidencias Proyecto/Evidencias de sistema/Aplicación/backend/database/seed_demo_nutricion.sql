INSERT INTO menu_preparacion
    (id_menu, id_preparacion, id_categoria_menu, id_tipo_componente, cantidad_planificada, precio)
SELECT m.id_menu, p.id_preparacion, c.id_categoria_menu, t.id_tipo_componente, dm.cantidad,
       CASE WHEN c.id_categoria_menu IS NOT NULL THEN p.precio END
FROM _demo_menu dm
JOIN menu m ON m.fecha = dm.fecha
          AND m.id_sede = (SELECT id_sede FROM sede ORDER BY id_sede LIMIT 1)
JOIN preparacion p ON p.nombre = dm.preparacion
JOIN tipo_componente t ON t.nombre = dm.tipo
LEFT JOIN categoria_menu c ON c.nombre = dm.categoria
WHERE NOT EXISTS (
    SELECT 1 FROM menu_preparacion x
    WHERE x.id_menu = m.id_menu
      AND x.id_tipo_componente = t.id_tipo_componente
      AND x.id_categoria_menu IS NOT DISTINCT FROM c.id_categoria_menu
);

